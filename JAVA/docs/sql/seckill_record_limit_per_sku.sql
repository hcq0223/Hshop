-- ======================================================================
-- 秒杀限购粒度调整：从「每活动一人一单」改为「每活动内每个商品每人限购」
--
-- 【为什么改】
--   原唯一索引是 (activity_id, user_id) —— 用户在同一个活动里买了一个商品，
--   同活动其它商品就再也买不了了。但电商秒杀的常规语义是：
--     活动是「场」（一场大促），商品才是「货」；
--     一人一单/限购应该落在「某个商品」上，而不是整个场次。
--   否则一个有 10 个商品的活动，顾客只能买走其中 1 个，活动形同虚设。
--
-- 【改动】
--   唯一索引 (activity_id, user_id) → (activity_id, user_id, sku_id)
--
--   Redis 侧的 Lua 脚本同步调整：
--     Set（SISMEMBER/SADD，只能表达买过/没买过）
--     → Hash（HGET/HINCRBY，field = userId:skuId，value = 已购件数）
--   这样才能支撑「每个商品限购 N 件」的累计判断。
--
--   ⚠️ DB 与 Redis 必须同时改：
--     只改 Redis → Redis 放行、DB 唯一索引仍拒绝第二次插入
--     只改 DB   → DB 放行、Redis 误判「已抢过」挡在门口
--
-- 【执行方式】
--   本脚本只做索引变更，不动数据。执行前请先备份 seckill_record。
-- ======================================================================

-- ----------------------------------------------------------------------
-- 1. 旧索引改为带 sku_id 的新索引
-- ----------------------------------------------------------------------
-- MySQL 不支持直接 RENAME 索引定义，只能 先删旧、再建新。
-- 两步之间若有并发写入，可能出现短暂的无唯一约束窗口 —— 建议停服或在活动间隙执行。
ALTER TABLE `seckill_record`
    DROP INDEX `uk_activity_user`;

ALTER TABLE `seckill_record`
    ADD UNIQUE KEY `uk_activity_user_sku` (`activity_id`, `user_id`, `sku_id`)
        COMMENT '同一活动内，同一用户在同一商品上只允许一条记录（限购 1 件/商品）';


