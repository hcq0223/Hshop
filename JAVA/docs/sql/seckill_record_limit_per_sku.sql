-- ----------------------------------------------------------------------
-- SHOW INDEX FROM seckill_record;
-- 期望看到：uk_activity_user_sku，字段顺序 activity_id, user_id, sku_id
-- 且不再有 uk_activity_user


-- ----------------------------------------------------------------------
-- 3. 说明：若希望「同一商品也允许多次购买、只是累计不超过 N 件」
-- ----------------------------------------------------------------------
-- 那么连唯一索引都不该有（否则第二次插入必然冲突），
-- 限购完全交给 Lua 脚本的 HINCRBY 累计判定 + 业务侧幂等。
-- 当前实现选择「每个商品限购 1 件」的强约束（DB 兜底），
-- 因为秒杀场景下「一人多单同商品」几乎没有业务价值，而唯一索引能提供
-- Redis 失效时的最后防线（Redis 数据可能因主从切换/过期而丢失）。
-- 若业务改成「限购 N 件」，需要同步：
--   1) 删除本唯一索引，改为普通索引 (activity_id, user_id, sku_id)
--   2) 依赖 Lua 脚本的 HINCRBY 累计判断限购
--   3) 在 seckill_record 增加 quantity 汇总校验或单独建「已购汇总表」
